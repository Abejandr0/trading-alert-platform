CREATE TABLE ticks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code VARCHAR(21) NOT NULL,
    price NUMERIC(24, 8) NOT NULL CHECK (price > 0),
    timestamp TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_ticks_asset_timestamp ON ticks (asset_code, timestamp DESC);

CREATE TABLE signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code VARCHAR(21) NOT NULL,
    signal VARCHAR(12) NOT NULL,
    reason VARCHAR(100) NOT NULL,
    price NUMERIC(24, 8) NOT NULL CHECK (price > 0),
    sma NUMERIC(24, 8) NOT NULL CHECK (sma > 0),
    timestamp TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_signals_asset_timestamp ON signals (asset_code, timestamp DESC);

CREATE TABLE signal_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code VARCHAR(21) NOT NULL,
    payload_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ
);
CREATE INDEX idx_signal_outbox_pending ON signal_outbox (created_at) WHERE published_at IS NULL;
